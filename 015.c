#include <stdio.h>

int main() {
    // 定义测试用的数字
    int a = 5;   // 二进制：0101
    int b = 3;   // 二进制：0011

    printf("===== 位运算全知识点演示 =====\n");
    printf("a = %d (二进制 0101)\n", a);
    printf("b = %d (二进制 0011)\n\n", b);

    // ==========================================
    // 1. 按位与 & ：两位都为1，结果才为1
    // ==========================================
    printf("1. 按位与 & ：a & b = %d\n", a & b);
    // 0101 & 0011 = 0001 → 1

    // ==========================================
    // 2. 按位或 | ：只要有一个1，结果就是1
    // ==========================================
    printf("2. 按位或 | ：a | b = %d\n", a | b);
    // 0101 | 0011 = 0111 →7

    // ==========================================
    // 3. 按位异或 ^ ：相同为0，不同为1
    // ==========================================
    printf("3. 按位异或 ^ ：a ^ b = %d\n", a ^ b);
    // 0101 ^ 0011 = 0110 →6

    // ==========================================
    // 4. 按位取反 ~ ：0变1，1变0
    // ==========================================
    printf("4. 按位取反 ~ ：~a = %d\n", ~a);
    // 对 0101 取反 → 1010（补码）→ 十进制 -6

    // ==========================================
    // 5. 左移 << ：整体左移，右边补0 → 等价 ×2
    // ==========================================
    printf("5. 左移 << ：a << 1 = %d\n", a << 1);
    // 0101 → 1010 → 10

    // ==========================================
    // 6. 右移 >> ：整体右移，左边补符号位 → 等价 ÷2
    // ==========================================
    printf("6. 右移 >> ：a >> 1 = %d\n", a >> 1);
    // 0101 → 0010 → 2

    printf("\n===== 位运算实用小技巧 =====\n");

    int x = 4; // 100
    // 技巧1：判断奇偶 (x & 1) == 1 → 奇数
    printf("技巧1：x 是奇数？%d (1=是,0=否)\n", x & 1);

    // 技巧2：交换两个数（不用临时变量）
    int m = 10, n = 20;
    m ^= n;
    n ^= m;
    m ^= n;
    printf("技巧2：交换 m、n → m=%d, n=%d\n", m, n);

    // 技巧3：乘以 2^n  用左移
    printf("技巧3：4 乘以 8 = %d\n", 4 << 3);

    // 技巧4：除以 2^n 用右移
    printf("技巧4：16 除以 4 = %d\n", 16 >> 2);

    return 0;
}